import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { CyberSentinels } from '../../../packages/cyber-sentinels-sdk/src/index.ts';
const directory='docs/release/v1-control-plane-production-proof';
const proof=JSON.parse(await readFile(`${directory}/customer-zero.json`,'utf8'));
const application=JSON.parse(await readFile(`${directory}/application-evidence.json`,'utf8'));
if(process.env.I_CONFIRM_PRODUCTION!=='kecgtsfibkypjuaxqbjx'||process.env.SUPABASE_SERVICE_ROLE_KEY) throw new Error('Public client credentials only');
const cs=new CyberSentinels({apiKey:process.env.CYBER_SENTINELS_API_KEY,baseUrl:proof.origin});
const runtime=await fetch(`${proof.origin}/api/ready`).then(response=>response.json());
assert.equal(runtime.status,'READY');
assert.equal(runtime.runtime.commitSha,proof.sourceSha);
const first=proof.stages.firstDecision.transaction_id;
const second=proof.stages.secondDecision.transaction_id;
proof.stages.firstReplayAfterReview=await cs.trust.getReplay(first);
proof.stages.firstTransactionAfterReview=await cs.trust.getTransaction(first);
assert.equal(proof.stages.firstTransactionAfterReview.decision,'ALLOW');
const before=application.stages.originalReceiptBefore.body;
const after=application.stages.originalReceiptAfter.body;
assert.equal(after.decision,before.decision);
assert.equal(after.decisionDigest,before.decisionDigest);
assert.deepEqual(after.reasonCodes,before.reasonCodes);
assert.equal(after.decisionOutcomeReview.originalDecision,'ALLOW');
assert.equal(after.decisionOutcomeReview.adjudicatedOutcome,'DENY');
assert.equal(after.decisionOutcomeReview.evaluationStatus,'CONTRADICTED');
const memory=application.stages.trustMemory.body.timeline.memory;
const firstMemory=memory.find(row=>row.memory_type==='CANONICAL_TRUST_TRANSACTION'&&row.source_id===first);
const secondMemory=memory.find(row=>row.memory_type==='CANONICAL_TRUST_TRANSACTION'&&row.source_id===second);
const reviewMemory=memory.find(row=>row.memory_type==='DECISION_OUTCOME_REVIEW'&&row.source_id===first);
assert.equal(firstMemory.summary.originalDecision,'ALLOW');
assert.equal(secondMemory.summary.originalDecision,'DENY');
assert.equal(secondMemory.summary.previousTransactionId,first);
assert.equal(reviewMemory.summary.originalDecision,'ALLOW');
assert.equal(reviewMemory.summary.laterAdjudication.adjudicatedOutcome,'DENY');
const graph=application.stages.evidenceGraph.body.graph;
assert.ok(graph.nodes.some(node=>node.externalId===proof.stages.authority.authority_id));
assert.ok(graph.nodes.some(node=>node.metadata?.canonicalTransactionId===first));
assert.ok(graph.nodes.some(node=>node.metadata?.canonicalTransactionId===second));
assert.ok(graph.edges.length>0);
const replayEvents=proof.stages.firstReplayAfterReview.events??proof.stages.firstReplayAfterReview.timeline??[];
assert.ok(JSON.stringify(replayEvents).includes('DECISION_OUTCOME_REVIEW_ATTACHED'));
proof.persistedEvidenceAudit={checkedAt:new Date().toISOString(),retrievedOnRuntimeSha:runtime.runtime.commitSha,originalDecisionImmutable:true,originalDigestImmutable:true,originalReasonCodesImmutable:true,firstMemory:firstMemory.memory_id,secondMemory:secondMemory.memory_id,reviewMemory:reviewMemory.memory_id,graphNodes:graph.nodes.length,graphEdges:graph.edges.length,outcomeReview:'ALLOW original preserved, DENY adjudication, CONTRADICTED; original decision, digest and reasons remain immutable'};
await writeFile(`${directory}/customer-zero.json`,JSON.stringify(proof,null,2));
console.log(JSON.stringify(proof.persistedEvidenceAudit));
