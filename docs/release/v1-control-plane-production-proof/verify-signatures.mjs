import assert from 'node:assert/strict';
import { createPublicKey, verify, createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { canonicalize } from '../../../src/lib/trust-core/canonicalize.ts';
const directory=process.argv[2];
const data=JSON.parse(await readFile(join(directory,'persisted-control-plane.json'),'utf8'));
const proof=JSON.parse(await readFile(join(directory,'customer-zero.json'),'utf8'));
const {credential,manifest,evidence}=data;
const publicKey=createPublicKey({key:credential.public_jwk,format:'jwk'});
const bytes=value=>Buffer.from(canonicalize(value),'utf8');
const hash=value=>createHash('sha256').update(bytes(value)).digest('hex');
const fingerprint=hash({crv:credential.public_jwk.crv,kty:credential.public_jwk.kty,x:credential.public_jwk.x});
assert.equal(fingerprint,credential.credential_fingerprint);
const signedManifest=manifest.manifest.signedPublicManifest;
assert.equal(hash(signedManifest),manifest.manifest_digest);
assert.ok(verify(null,bytes(signedManifest),publicKey,Buffer.from(manifest.manifest.signature,'base64url')));
assert.equal(evidence.length,4,'Exactly two accepted atomic pairs; rejected heartbeats add no rows');
const eventIds=new Set();
for(const row of evidence) {
  const f=row.normalized_facts,h=f.heartbeat;
  const {agent_id,credential_id,event_id,issued_at,environment,authority_id,policy_id,policy_version}=h;
  assert.equal(agent_id,proof.stages.agent.agent_id); assert.equal(credential_id,credential.credential_id);
  assert.equal(f.subject.tenantId,proof.stages.agent.manifest_context.enterprise_id);
  assert.equal(f.observation.audience,`${proof.origin}/api/v1`);
  assert.ok(verify(null,bytes({domain:'cyber-sentinels:control-plane-heartbeat:v1',audience:f.observation.audience,tenant_id:f.subject.tenantId,agent_id,credential_id,event_id,issued_at,environment,authority_id,policy_id,policy_version}),publicKey,Buffer.from(h.signature,'base64url')));
  assert.equal(hash(f),row.payload_hash); assert.equal(f.baseline.credentialFingerprint,fingerprint);
  assert.equal(f.baseline.manifestDigest,manifest.manifest_digest);
  assert.equal(f.baseline.runtimeConfigurationDigest,hash({runtime:signedManifest.runtime}));
  assert.equal(f.baseline.modelConfigurationDigest,hash({model:signedManifest.model}));
  assert.equal(f.baseline.declaredCapabilitiesDigest,hash({capabilities:signedManifest.declared_capabilities}));
  assert.equal(row.server_verified,true); assert.equal(row.cryptographically_verified,true);
  assert.equal(row.source_type,'CYBER_SENTINELS_CONTROL_PLANE_VERIFIED');
  assert.equal(f.monitoring.downstreamExecutionObserved,false);
  const age=Date.parse(f.observation.observedAt)-Date.parse(issued_at);
  assert.ok(age>=-30000&&age<=120000);
  assert.ok(Date.parse(row.expires_at)<=Date.parse(issued_at)+300000);
  eventIds.add(event_id);
}
assert.equal(eventIds.size,2);
const result={status:'PASS',verifiedAt:new Date().toISOString(),manifestSignature:true,heartbeatSignatures:evidence.length,acceptedEvents:eventIds.size,atomicPairs:2,payloadHashes:true,configurationDigestsFromSignedClaims:true,credentialFingerprint:true,heartbeatFreshness:true,publicKeyOnly:true};
await writeFile(join(directory,'offline-signature-verification.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
